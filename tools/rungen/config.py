"""Числа баланса. Значения по умолчанию — подобранные (см. balance.py и README.md).

START_5_8 — стартовая точка из раздела 5.8 DESIGN.md, с неё начат подбор.
"""

from dataclasses import dataclass, replace


@dataclass(frozen=True)
class Config:
    # --- Правила игры (переносятся в Unreal) ---
    items_in_run: int = 16          # предметов в забеге (6 значимых + пустышки), 5.4
    health: int = 4                 # сколько попаданий убивает, 5.8: «на 4–5 попаданий»
    p_meaningful: float = 0.18      # шанс аномалии в комнате на цепочке, 5.8: ~15%
    p_guess: float = 0.85           # шанс аномалии в комнате-догадке, 5.8: 80–90%
    p_target: float = 0.20          # шанс, что в копии комнаты цепочки лежит нужный следующий предмет
    target_guarantee_by: int = 5    # нужный предмет гарантированно лежит в одной из первых N копий (0 = без гарантии)
    filler_min: int = 2             # прочих предметов в копии комнаты: от
    filler_max: int = 3             # до
    dummy_weight: int = 1           # вес пустышки при раскладке прочих предметов
    false_weight: int = 1           # вес ложного значимого предмета (X, Y)
    doors_min: int = 2              # нераскрытых дверей в новой комнате, кроме входной, 5.2
    doors_max: int = 3
    p_extra_note: float = 0.5       # шанс дополнительной записки в комнате цепочки
    p_guess_note: float = 0.3       # шанс записки в комнате-догадке (только «бесполезен»/«опасен»)

    # --- Модель игрока (только для симуляции, в игру не переносится) ---
    p_hit: float = 1.0              # шанс получить урон при входе в комнату с действующей аномалией
    p_fix: float = 0.5              # шанс устранить аномалию за визит; устранённая в этой копии больше не бьёт
    max_entries: int = 400          # предел входов в комнаты, после него забег считается зависшим


DEFAULT = Config()

START_5_8 = replace(
    DEFAULT,
    health=4,
    p_meaningful=0.15,
    p_guess=0.85,
    p_target=0.35,
    target_guarantee_by=3,
)
