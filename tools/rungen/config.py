"""Числа баланса. Значения по умолчанию — подобранные (см. balance.py и README.md)."""

from dataclasses import dataclass, replace


@dataclass(frozen=True)
class Config:
    # --- Правила игры (переносятся в Unreal) ---
    items_in_run: int = 16          # предметов в забеге (6 значимых + пустышки), 5.4
    health: int = 4                 # сколько попаданий убивает, 5.8: «на 4–5 попаданий»
    p_guess: float = 1.0            # доля неправильных наборов с аномалией: все. У правильных аномалий нет
    filler_min: int = 3             # прочих предметов в комнате, кроме предмета правильного пути: от
    filler_max: int = 4             # до
    extras: int = 8                 # лишних значимых предметов: в правильный путь не входят, дают неправильные сочетания
    dummy_weight: int = 2           # вес пустышки при раскладке прочих предметов
    extra_weight: int = 5           # вес лишнего значимого предмета при раскладке
    p_extra_note: float = 0.5       # шанс второй записки в комнате правильного пути
    p_guess_note: float = 0.3       # шанс записки в комнате-догадке (только «бесполезен»/«опасен»)

    # --- Модель игрока (только для симуляции, в игру не переносится) ---
    p_hit: float = 1.0              # шанс получить урон при входе в комнату с действующей аномалией
    p_fix: float = 0.5              # шанс устранить аномалию за визит; устранённая в этой копии больше не бьёт
    max_entries: int = 400          # предел входов в комнаты, после него забег считается зависшим


DEFAULT = Config()
