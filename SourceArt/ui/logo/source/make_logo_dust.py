"""Logo dust: the last letters of PERIBOTHRON crumble and their pixels spiral into the black hole of the menu.

    /opt/homebrew/bin/python3 -I SourceArt/ui/logo/source/make_logo_dust.py [preview.png]

Reads T_Logo.png and writes Source/MegaJam/Menu/LogoDust.h: the letters right of the gap before the second R ("RON")
cut into CELL x CELL texel chunks, each with its place in the texture and its eat value (0..65535). AMenuHUD draws
the logo left of the gap as one tile and these chunks one by one with their own piece of the texture, so the intact
letters look exactly like the texture. A chunk whose eat value is above the current threshold is gone; just above
the threshold it hangs loose next to its place; just below it is the crumbling edge, and the stream of pixels flying
to the black hole is born there (AMenuHUD::DrawLogo). Fixed seed: the same edge every run.
Eat value: further right (closer to the end of the word) and higher up (the hole is above the logo) is eaten first,
plus value noise on two scales for a ragged edge. Normalised to 0..1 over the chunks.
With a path argument the script also writes a preview: the logo at the start threshold and at the limit.
"""
import math
import os
import random
import sys

from PIL import Image

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROJECT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
OUT = os.path.join(PROJECT, "Source", "MegaJam", "Menu", "LogoDust.h")
CELL = 3
SEED = 7
NOISE = 0.35                   # weight of the noise against the left-to-right order
T_START, T_LIMIT = 0.80, 0.73  # eaten above the threshold: at the start and the limit it never reaches (AMenuHUD)


def value_noise(rng, scale, w, h):
    gw, gh = int(w / scale) + 2, int(h / scale) + 2
    grid = [[rng.random() for _ in range(gw)] for _ in range(gh)]

    def at(x, y):
        fx, fy = x / scale, y / scale
        ix, iy = int(fx), int(fy)
        tx, ty = fx - ix, fy - iy
        tx, ty = tx * tx * (3 - 2 * tx), ty * ty * (3 - 2 * ty)
        a = grid[iy][ix] + (grid[iy][ix + 1] - grid[iy][ix]) * tx
        b = grid[iy + 1][ix] + (grid[iy + 1][ix + 1] - grid[iy + 1][ix]) * tx
        return a + (b - a) * ty
    return at


def main():
    logo = Image.open(os.path.join(HERE, "T_Logo.png")).convert("RGBA")
    w, h = logo.size
    alpha = logo.getchannel("A")
    px = alpha.load()
    # letters = runs of columns with ink; the dust starts in the gap before the third letter from the end
    ink = [any(px[x, y] > 8 for y in range(h)) for x in range(w)]
    runs, x = [], 0
    while x < w:
        if ink[x]:
            x0 = x
            while x < w and ink[x]:
                x += 1
            runs.append((x0, x))
        x += 1
    assert len(runs) == 11, f"expected 11 letters in PERIBOTHRON, found {len(runs)}: {runs}"
    split = (runs[7][1] + runs[8][0]) // 2           # between H and R
    split -= split % CELL
    end = runs[-1][1]
    rng = random.Random(SEED)
    coarse, fine = value_noise(rng, 22.0, w, h), value_noise(rng, 7.0, w, h)
    chunks = []
    for cy in range(0, h - h % CELL, CELL):
        for cx in range(split, w - (w - split) % CELL, CELL):
            a = max(px[cx + i, cy + j] for i in range(CELL) for j in range(CELL))
            if a <= 8:
                continue
            mx, my = cx + CELL / 2, cy + CELL / 2
            u = (mx - split) / (end - split)
            n = 0.7 * coarse(mx, my) + 0.3 * fine(mx, my)
            e = u + NOISE * (n - 0.5) + 0.08 * (0.5 - my / h)
            chunks.append([cx, cy, e])
    lo, hi = min(c[2] for c in chunks), max(c[2] for c in chunks)
    for c in chunks:
        c[2] = round((c[2] - lo) / (hi - lo) * 65535)
    with open(OUT, "w") as f:
        f.write("// Generated by SourceArt/ui/logo/source/make_logo_dust.py from T_Logo.png. Do not edit.\n")
        f.write("// Chunks of the last letters of the logo: texel place (top left) and eat value (0..65535), see AMenuHUD.\n")
        f.write("#pragma once\n\n#include \"CoreMinimal.h\"\n\nnamespace LogoDust\n{\n")
        f.write(f"\tconstexpr int32 Cell = {CELL};\n\tconstexpr int32 SplitX = {split};      // texels left of it: one tile\n")
        f.write(f"\tconstexpr int32 TexW = {w};\n\tconstexpr int32 TexH = {h};\n")
        f.write(f"\tconstexpr float StartThreshold = {T_START}f;\n\tconstexpr float LimitThreshold = {T_LIMIT}f;\n")
        f.write("\tstruct FChunk { uint16 X; uint16 Y; uint16 Eat; };\n")
        f.write(f"\tconstexpr int32 Num = {len(chunks)};\n\tconstexpr FChunk Chunks[Num] = {{\n")
        for i in range(0, len(chunks), 8):
            f.write("\t\t" + " ".join(f"{{{x}, {y}, {e}}}," for x, y, e in chunks[i:i + 8]) + "\n")
        f.write("\t};\n}\n")
    print(f"{os.path.relpath(OUT, PROJECT)}: {len(chunks)} chunks, split at x = {split} of {w}, letters {runs[8:]}")

    if len(sys.argv) > 1:
        rows = []
        for t in (T_START, T_LIMIT):
            im = Image.new("RGBA", (w, h), (20, 22, 30, 255))
            left = logo.crop((0, 0, split, h))
            im.alpha_composite(left, (0, 0))
            for cx, cy, e in chunks:
                if e / 65535 <= t:
                    im.alpha_composite(logo.crop((cx, cy, cx + CELL, cy + CELL)), (cx, cy))
            rows.append(im)
        sheet = Image.new("RGBA", (w, 2 * h + 10), (255, 0, 255, 255))
        sheet.alpha_composite(rows[0], (0, 0))
        sheet.alpha_composite(rows[1], (0, h + 10))
        sheet.convert("RGB").save(sys.argv[1])


if __name__ == "__main__":
    main()
